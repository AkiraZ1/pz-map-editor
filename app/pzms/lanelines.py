def _pd(px, py, s):
    ax, ay, bx, by = s
    dx, dy = bx - ax, by - ay
    L2 = dx * dx + dy * dy or 1e-9
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / L2))
    return math.hypot(px - ax - t * dx, py - ay - t * dy)


def clip(c, gx, gy):
    """segmento da reta c + gx*(u-.5) + gy*(v-.5) = 0 dentro do quadrado [0,1]^2, ou None."""
    P = []
    for u in (0.0, 1.0):
        if abs(gy) > 1e-9:
            v = 0.5 - (c + gx * (u - 0.5)) / gy
            if -1e-9 <= v <= 1 + 1e-9:
                P.append((u, min(1.0, max(0.0, v))))
    for v in (0.0, 1.0):
        if abs(gx) > 1e-9:
            u = 0.5 - (c + gy * (v - 0.5)) / gx
            if -1e-9 <= u <= 1 + 1e-9:
                P.append((min(1.0, max(0.0, u)), v))
    if len(P) < 2:
        return None
    a = P[0]
    b = max(P[1:], key=lambda p: math.hypot(p[0] - a[0], p[1] - a[1]))
    return (a[0], a[1], b[0], b[1])


def best(s, tol=0.17):
    """id do sprite cujo traco mais se parece com o segmento s (distancia de Hausdorff entre os dois)."""
    bi, bd = None, tol
    for i, g in SEG.items():
        d = max(_pd(g[0], g[1], s), _pd(g[2], g[3], s), _pd(s[0], s[1], g), _pd(s[2], s[3], g))
        if d < bd:
            bi, bd = i, d
    return bi


